const fs = require("fs");
const path = require("path");

/**
 * Regenerates IconIds.kt from the icons/ folder. Run after adding or removing icons:
 *   node scripts/generate-registry.js
 */
const sourceFolder = path.resolve(__dirname, "..", "icons");
const outFile = path.resolve(__dirname, "..", "icon-tree-animate/src/main/kotlin/com/icontree/animate/IconIds.kt");

const names = fs.readdirSync(sourceFolder).filter((f) => f.endsWith(".json")).sort()
  .map((f) => f.replace(/(\.json)+$/, "")).filter(Boolean);
if (!names.length) { console.error(`No .json files in ${sourceFolder}`); process.exit(1); }

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$");
fs.writeFileSync(outFile, `// Auto-generated by scripts/generate-registry.js. Do not edit.
// Icon data is bundled in the library's assets; no runtime network requests are made.
package com.icontree.animate

/** Every bundled icon ID, sorted. */
val iconIds: List<String> = listOf(
${names.map((n) => `    "${esc(n)}",`).join("\n")}
)
`);
console.log(`Wrote ${names.length} icon ids`);
